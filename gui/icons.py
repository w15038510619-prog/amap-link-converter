def get_icon(name: str, color: str = "#0066CC", size: int = 16) -> QIcon:
    """生成指定颜色与尺寸的矢量 QIcon"""
    svg_tpl = SVG_ICONS.get(name)
    if not svg_tpl:
        return QIcon()

    svg_content = svg_tpl.format(color=color).strip()
    pix = QPixmap(size, size)
    pix.fill(Qt.transparent)  # 透明背景
    pix.loadFromData(QByteArray(svg_content.encode("utf-8")))
    return QIcon(pix)


def get_pixmap(name: str, color: str = "#0066CC", size: int = 24) -> QPixmap:
    """生成指定颜色与尺寸的 QPixmap"""
    svg_tpl = SVG_ICONS.get(name)
    if not svg_tpl:
        return QPixmap()

    svg_content = svg_tpl.format(color=color).strip()
    pix = QPixmap(size, size)
    pix.fill(Qt.transparent)
    pix.loadFromData(QByteArray(svg_content.encode("utf-8")))
    return pix
